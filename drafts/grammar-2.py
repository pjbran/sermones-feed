# Grammar 2 · Sentences inside sentences (quī / quae / quod; quem / quam / quōs; says that = accusative + infinitive)
# Line types: ["t", English talk, {Latin} in braces] · ["p", English, Latin] · ["q", Latin, English] (ear quiz)
# Rules: Patrick's known words (from his Forms > Patterns items), present/perfect indicative + present infinitive only,
# male endings, NO rīdeō, A2. Running gag: Sextus, the colleague who drinks my coffee. Teaser for Grammar 3: who tells the truth?
# Length: Grammar 1 = 135 lines / 94 Latin; target about +35%.
import json
L = []
t = lambda s: L.append(["t", s])
p = lambda en, la: L.append(["p", en, la])
q = lambda la, en: L.append(["q", la, en])

# ---------------- intro + quick review of Grammar 1 ----------------
t("{Salvē!} Welcome back to the Grammar series. Episode two: sentences inside sentences.")
t("First, a quick warm-up from last time. Four kinds of link.")
p("When I am tired, I drink coffee.", "Cum fessus sum, caffeam bibō.")
p("I am angry because my colleague drinks my coffee.", "Īrātus sum quod collēga caffeam meam bibit.")
p("Unless I hurry, my colleague drinks my coffee.", "Nisi festīnō, collēga caffeam meam bibit.")
p("Although the coffee is mine, my colleague still drinks it.", "Quamquam caffea mea est, collēga tamen eam bibit.")
t("Last time I asked two questions. Who is this colleague? And what does he say?")
t("Today you get the tools to answer both. Tool one: who and which. Tool two: says that.")

# ---------------- 1. two become one: quī / quae / quod ----------------
t("Part one. Two become one.")
t("Here are two plain sentences about the same friend.")
p("The friend helps the colleague.", "Amīcus collēgam adiuvat.")
p("The friend is good.", "Amīcus bonus est.")
t("Now fold the first one inside the second, with {quī}.")
p("The friend who helps the colleague is good.", "Amīcus quī collēgam adiuvat bonus est.")
t("Again. Two sentences about one woman.")
p("The woman loves the dog.", "Fēmina canem amat.")
p("The woman who loves the dog is happy.", "Fēmina quae canem amat laeta est.")
t("And one about the teacher.")
p("The teacher teaches the students.", "Magister discipulōs docet.")
p("The teacher who teaches the students is tired.", "Magister quī discipulōs docet fessus est.")
t("The rule. {Quī}, {quae} or {quod} starts a mini-sentence. It tells you more about the noun just before it.")
t("{Quī} for a man. {Quae} for a woman. {Quod} for a neuter word.")
t("But in Latin, things have a gender too. {Caffea} is like a woman, so: {caffea quam}. {Lectus} is like a man, so: {lectus quem}. Match the noun.")
t("Spot it: a noun, then {quī}, {quae} or {quod}. Read: who, or which.")
t("Now we build. Our mystery colleague.")
p("The colleague...", "Collēga...")
p("The colleague who...", "Collēga quī...")
p("The colleague who drinks coffee...", "Collēga quī caffeam bibit...")
p("The colleague who drinks my coffee...", "Collēga quī caffeam meam bibit...")
p("The colleague who drinks my coffee is Sextus.", "Collēga quī caffeam meam bibit Sextus est.")
p("The colleague who drinks my coffee every day is Sextus.", "Collēga quī caffeam meam cotīdiē bibit Sextus est.")
p("Sextus! Of course.", "Sextus! Certē.")
p("Sextus is the colleague who drinks my coffee.", "Sextus est collēga quī caffeam meam bibit.")
t("Now a woman, with {quae}.")
p("The colleague who makes the coffee is Claudia.", "Collēga quae caffeam parat Claudia est.")
p("Claudia is the colleague who makes good coffee.", "Claudia est collēga quae caffeam bonam parat.")
t("And a thing, with {quod}.")
p("The computer is on the table.", "Computātrum in mēnsā est.")
p("The computer which is on the table is mine.", "Computātrum quod in mēnsā est meum est.")
p("The computer which is on the table is old.", "Computātrum quod in mēnsā est vetus est.")
t("Notice: the noun comes first, then the {quī} part, then the rest of the main sentence. The {quī} part often sits in the middle, like a filling.")

# ---------------- 2. the trap: quem / quam / quōs ----------------
t("Part two. The trap. Who does it, and who gets it.")
t("With {quī} or {quae}, the noun does the action. With {quem} or {quam}, the action is done to the noun.")
t("Listen to the difference.")
p("The friend who is waiting for the man is busy.", "Amīcus quī virum exspectat occupātus est.")
p("The friend whom the man is waiting for is busy.", "Amīcus quem vir exspectat occupātus est.")
t("Same friend. In the first, he waits. In the second, someone waits for him.")
p("The boy who is afraid of the neighbour...", "Puer quī vīcīnum timet...")
p("The neighbour whom the boy is afraid of is angry.", "Vīcīnus quem puer timet īrātus est.")
p("The dog that the woman hears is fierce.", "Canis quem mulier audit ferus est.")
t("The rule. {Quem} for a man, {quam} for a woman. {Quod} for a neuter word, both ways. For many people: {quōs}.")
t("Spot it: {quem}, {quam}, {quōs}. Someone else does the action. Look for a new subject, or a verb ending that tells you who does it.")
t("Build it, with our coffee.")
p("The coffee...", "Caffea...")
p("The coffee which Claudia made...", "Caffea quam Claudia parāvit...")
p("The coffee which Claudia made is excellent.", "Caffea quam Claudia parāvit optima est.")
p("Sextus drinks the coffee.", "Sextus caffeam bibit.")
p("Sextus drinks the coffee which Claudia made.", "Sextus caffeam quam Claudia parāvit bibit.")
p("Sextus drinks the coffee which I bought.", "Sextus caffeam quam ego ēmī bibit.")
p("Of course he does.", "Certē.")
t("Now who does it, and who gets it, side by side.")
p("The colleague who is waiting for me...", "Collēga quī mē exspectat...")
p("The colleague whom I am waiting for...", "Collēga quem exspectō...")
p("The colleague whom I am waiting for is Sextus.", "Collēga quem exspectō Sextus est.")
p("The colleague who is looking for me is Claudia.", "Collēga quae mē quaerit Claudia est.")
p("The colleague whom I am looking for is Sextus.", "Collēga quem quaerō Sextus est.")
t("One more pair. Listen to the first word after the noun.")
p("The doctor who called the neighbour...", "Medicus quī vīcīnum vocāvit...")
p("The doctor whom the neighbour called is coming soon.", "Medicus quem vīcīnus vocāvit mox venit.")
p("The woman who greeted the teacher...", "Fēmina quae magistrum salūtāvit...")
p("The woman whom the teacher greeted...", "Fēmina quam magister salūtāvit...")
p("The students are watching the woman whom the teacher greeted.", "Discipulī fēminam quam magister salūtāvit spectant.")
t("And many people, with {quōs}.")
p("The guests whom the colleagues invited are already here.", "Hospitēs quōs collēgae invītāvērunt iam adsunt.")
p("The students whom the teacher praises are glad.", "Discipulī quōs magister laudat gaudent.")

# ---------------- 3. quod: which or because? ----------------
t("Part three. {Quod}: which, or because?")
t("Last time, {quod} meant because. Today it also means which. How do you know?")
t("If {quod} comes right after a thing and tells you more about it: which. If it gives a reason: because.")
p("We drink the wine which Marcus bought.", "Vīnum quod Mārcus ēmit bibimus.")
p("We drink wine because Marcus is coming.", "Vīnum bibimus quod Mārcus venit.")
p("The plan which the company proposed is difficult.", "Cōnsilium quod societās prōposuit difficile est.")
p("I do not approve of the plan because the company has no money.", "Cōnsilium nōn probō quod societās pecūniam nōn habet.")
t("Listen for the gap. With which, something is missing in the mini-sentence: Marcus bought, bought what? The wine. With because, nothing is missing.")

# ---------------- 4. says that ----------------
t("Part four. Says that.")
t("In English we say: Julia says that Marcus is coming. In Latin there is no word for that.")
t("Instead, two small changes. Listen to the plain sentence, then the says-that version.")
p("Marcus is coming today.", "Mārcus hodiē venit.")
p("Julia says that Marcus is coming today.", "Iūlia dīcit Mārcum hodiē venīre.")
t("{Mārcus} became {Mārcum}. {Venit} became {venīre}.")
p("The sky is clear today.", "Caelum hodiē clārum est.")
p("They say that the sky is clear today.", "Dīcunt caelum hodiē clārum esse.")
p("Gaius is tired and sad.", "Gāius fessus et trīstis est.")
p("I think that Gaius is tired and sad.", "Putō Gāium fessum et trīstem esse.")
t("The rule. After say, think, know, see, hear, believe, hope or deny, the subject goes into the object form. {Mārcus} becomes {Mārcum}. {Amīcī} becomes {amīcōs}. {Ego} becomes {mē}.")
t("Describing words change with it. {Fessus} becomes {fessum}. And the verb goes into the infinitive, like {venīre}. {Est} becomes {esse}.")
t("Spot it: a say or think verb, then a word in the object form, then an infinitive. Read: that.")
t("Now the pyramid. Who says it. Here is the plain fact.")
p("Sextus drinks my coffee.", "Sextus caffeam meam bibit.")
p("I say that Sextus drinks my coffee.", "Dīcō Sextum caffeam meam bibere.")
p("I think that Sextus drinks my coffee.", "Putō Sextum caffeam meam bibere.")
p("I know that Sextus drinks my coffee.", "Sciō Sextum caffeam meam bibere.")
p("I see that Sextus is drinking my coffee.", "Videō Sextum caffeam meam bibere.")
p("Claudia says that Sextus drinks my coffee.", "Claudia dīcit Sextum caffeam meam bibere.")
p("All my colleagues believe that Sextus drinks my coffee.", "Omnēs collēgae meī crēdunt Sextum caffeam meam bibere.")
t("And what does Sextus say?")
p("Sextus says that the coffee is his.", "Sextus dīcit caffeam suam esse.")
p("Sextus says that the coffee is not mine.", "Sextus negat caffeam meam esse.")
p("Sextus says that I am wrong.", "Sextus dīcit mē errāre.")
p("I say that you are wrong, Sextus!", "Dīcō tē errāre, Sexte!")
p("I hope that Sextus buys his own coffee.", "Spērō Sextum caffeam suam emere.")
p("I do not believe that Sextus buys coffee.", "Nōn crēdō Sextum caffeam emere.")
t("Careful with {negō}. It means: I say that it is not so. The not is inside the verb.")
p("Marcus says that Publius is not at home.", "Mārcus negat Pūblium domī esse.")
t("And {mē} and {tē} work the same way.")
p("I hope that you are well.", "Spērō tē bene valēre.")
p("Gaius knows that you are busy this week.", "Gāius scit tē hāc hebdomade occupātum esse.")
p("Sextus thinks that we work too much.", "Sextus putat nōs nimis labōrāre.")
t("The main verb can be in the past too. The re verb stays the same.")
p("Yesterday Marcus said that Quintus was at the gym.", "Mārcus herī dīxit Quīntum in gymnasiō esse.")
p("I heard that Flavia has a new job at the bank.", "Audīvī Flāviam novum mūnus in argentāriā habēre.")
p("Yesterday Claudia said that Sextus was drinking my coffee.", "Claudia herī dīxit Sextum caffeam meam bibere.")
p("And today?", "Et hodiē?")
p("Today I see that Sextus is drinking my coffee.", "Hodiē videō Sextum caffeam meam bibere.")

# ---------------- 5. both tools together ----------------
t("Part five. Both tools together. A sentence inside a sentence, inside a sentence.")
p("Claudia says that...", "Claudia dīcit...")
p("Claudia says that the colleague is Sextus.", "Claudia dīcit collēgam Sextum esse.")
p("Claudia says that the colleague who drinks my coffee is Sextus.", "Claudia dīcit collēgam quī caffeam meam bibit Sextum esse.")
t("Notice: {quī}, not {quem}. Inside its own mini-sentence, the colleague does the drinking.")
p("I think that the coffee which Claudia made is excellent.", "Putō caffeam quam Claudia parāvit optimam esse.")
p("Sextus says that the coffee which he drinks is not mine.", "Sextus negat caffeam quam bibit meam esse.")
t("And with a link word from last time.")
p("Although Sextus says that the coffee is his, it is still mine.", "Quamquam Sextus dīcit caffeam suam esse, tamen mea est.")
p("Because Sextus drinks my coffee, I am angry.", "Quod Sextus caffeam meam bibit, īrātus sum.")
p("If Sextus says that I am wrong, I do not believe him.", "Sī Sextus dīcit mē errāre, eī nōn crēdō.")

# ---------------- 5b. swap the frame ----------------
t("Now swap the frame. One plain fact. Then the same fact as who, as whom, and as says that.")
p("Claudia makes the coffee.", "Claudia caffeam parat.")
p("Claudia, who makes the coffee, is kind.", "Claudia, quae caffeam parat, benigna est.")
p("The coffee which Claudia makes is excellent.", "Caffea quam Claudia parat optima est.")
p("I know that Claudia makes the coffee.", "Sciō Claudiam caffeam parāre.")
p("Sextus says that he makes the coffee.", "Sextus dīcit sē caffeam parāre.")
p("Sextus is wrong.", "Sextus errat.")
t("{Sē} means he himself: the same person as the main subject. {Sextus dīcit sē} means Sextus is talking about Sextus. {Suam}, from before, is the same idea: his own.")
p("Sextus says that he makes the coffee, but Claudia makes it.", "Sextus dīcit sē caffeam parāre, sed Claudia eam parat.")
p("Sextus thinks that he is never wrong.", "Sextus putat sē numquam errāre.")
t("Again, with the dog.")
p("The dog sleeps on the bed.", "Canis in lectō dormit.")
p("The dog that sleeps on the bed is mine.", "Canis quī in lectō dormit meus est.")
p("The bed which the dog loves is mine.", "Lectus quem canis amat meus est.")
p("I see that the dog is sleeping on the bed.", "Videō canem in lectō dormīre.")
p("Although I say that the bed is mine, the dog still sleeps on it.", "Quamquam dīcō lectum meum esse, canis tamen in eō dormit.")

# ---------------- 6. ear quiz ----------------
t("Ear quiz. You hear the Latin, then a short pause. Say the English in your head. Then I give you the answer. Watch out for {quī} and {quem}.")
q("Iuvenis quī senem adiuvat fortis est.", "The young man who helps the old man is strong.")
q("Medicus quem vīcīnus vocāvit mox venit.", "The doctor whom the neighbour called is coming soon.")
q("Librum Latīnum quem Titus scrīpsit legō.", "I am reading the Latin book that Titus wrote.")
q("Fēminae puerum quī bene cantat audiunt.", "The women hear the boy who sings well.")
q("Caffeam dulcem quam Iūlia parāvit valdē amō.", "I really love the sweet coffee that Julia made.")
q("Vīnum rubrum quod Mārcus ēmit vesperī bibimus.", "In the evening we drink the red wine that Marcus bought.")
q("Videō canem meum in lectō dormīre.", "I see that my dog is sleeping on the bed.")
q("Spērō amīcōs nostrōs mox venīre.", "I hope that our friends are coming soon.")
q("Audiō Lūcium quoque linguam Latīnam discere.", "I hear that Lucius is learning Latin too.")
q("Cornēlia crēdit Mārcum numquam errāre.", "Cornelia believes that Marcus is never wrong.")
q("Medicus dīcit Lūcium nōndum sānum esse.", "The doctor says that Lucius is not yet healthy.")
q("Putō linguam Graecam valdē difficilem esse.", "I think that Greek is very difficult.")
q("Hospitēs quōs vīcīnī invītāvērunt adhūc in urbe manent.", "The guests whom the neighbours invited are still in the city.")
q("Vīcīnus meus putat raedam meam rubram nimis cāram esse.", "My neighbour thinks that my red car is too expensive.")
q("Discipulus quem magister quaerit nunc in culīnā prandium edit.", "The student whom the teacher is looking for is now eating lunch in the kitchen.")
q("Flāvia negat novum programma ūtile esse.", "Flavia says that the new program is not useful.")
q("Interpres quem hospes quaerit Graecus est.", "The translator whom the guest is looking for is Greek.")
q("Vigilēs virum quī in mercātū clāmat spectant.", "The police are watching the man who is shouting in the market.")
q("Sciō Claudiam in oppidō parvō habitāre.", "I know that Claudia lives in a small town.")
q("Iūlia spērat Mārcum post labōrem statim ad cēnam venīre.", "Julia hopes that Marcus is coming to dinner straight after work.")
q("Cibum quem Cornēlia coxit omnēs laudant.", "Everyone praises the food that Cornelia cooked.")
q("Sextus putat nōs saepe vesperī nimis labōrāre.", "Sextus thinks that we often work too much in the evening.")

# ---------------- recap + teaser ----------------
t("Recap. Four key lines.")
p("The colleague who drinks my coffee is Sextus.", "Collēga quī caffeam meam bibit Sextus est.")
p("Sextus drinks the coffee which I bought.", "Sextus caffeam quam ego ēmī bibit.")
