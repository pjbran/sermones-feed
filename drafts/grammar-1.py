# Grammar 1 · Link words (cum / ubi / postquam, quod / quia, sī / nisi, quamquam … tamen)
# Line types: ["t", English talk, {Latin} in braces] · ["p", English, Latin] · ["q", Latin, English] (ear quiz)
# Rules: Patrick's ~1,060 known words (all from his Forms > Patterns items), present/perfect indicative only,
# male endings, NO rīdeō, A2. Running gag: the colleague who drinks my coffee (teaser for Grammar 2: quī).
import json
L = []
t = lambda s: L.append(["t", s])
p = lambda en, la: L.append(["p", en, la])
q = lambda la, en: L.append(["q", la, en])

# ---------------- intro ----------------
t("{Salvē!} Welcome to the Grammar series. Episode one: link words.")
t("Today you get four kinds of link word. Each one glues two sentences together, and each one changes the meaning.")
t("Here are two plain sentences.")
p("My colleague comes.", "Collēga venit.")
p("I drink coffee.", "Caffeam bibō.")
t("Now the same two sentences, with a different link each time. Listen to the first word.")
p("When my colleague comes, I drink coffee.", "Cum collēga venit, caffeam bibō.")
p("Because my colleague comes, I drink coffee.", "Quod collēga venit, caffeam bibō.")
p("If my colleague comes, I drink coffee.", "Sī collēga venit, caffeam bibō.")
p("Although my colleague comes, I drink coffee.", "Quamquam collēga venit, caffeam bibō.")
t("Same words. Four different stories. One word at the front changes everything.")
t("Let's take them one at a time.")

# ---------------- 1. when / after ----------------
t("Part one. When, and after.")
t("{Cum} means when. {Ubi} also means when. {Postquam} means after.")
t("Not the {cum} that means with. This {cum} starts a whole mini-sentence, with its own verb.")
t("First, a plain sentence. Then the same idea with a when-word.")
p("Marcus comes.", "Mārcus venit.")
p("When Marcus comes, I am happy.", "Cum Mārcus venit, laetus sum.")
p("I am tired.", "Fessus sum.")
p("When I am tired, I drink coffee.", "Cum fessus sum, caffeam bibō.")
p("Titus came back home.", "Titus domum rediit.")
p("When Titus came back home, he had dinner.", "Ubi Titus domum rediit, cēnāvit.")
p("Julia read the book.", "Iūlia librum lēgit.")
p("After Julia read the book, she slept.", "Postquam Iūlia librum lēgit, dormīvit.")
t("The rule. The when-part usually sits at the front, then a comma, then the main sentence. Its verb is a normal verb.")
t("Spot it: {cum}, {ubi} or {postquam} starts a mini-sentence. Its verb comes at the end, then a comma.")
t("Now we build. One word at a time.")
p("When my colleague comes...", "Cum collēga venit...")
p("When my colleague comes, I drink coffee.", "Cum collēga venit, caffeam bibō.")
p("When my colleague comes, I drink my coffee.", "Cum collēga venit, caffeam meam bibō.")
p("When my colleague comes into the office, I drink my coffee.", "Cum collēga in officium venit, caffeam meam bibō.")
p("When my colleague comes into the office, I drink my coffee quickly.", "Cum collēga in officium venit, caffeam meam celeriter bibō.")
p("Why quickly?", "Cūr celeriter?")
p("When my colleague came in...", "Ubi collēga intrāvit...")
p("When my colleague came in, I drank my coffee at once.", "Ubi collēga intrāvit, caffeam meam statim bibī.")
p("After my colleague came in...", "Postquam collēga intrāvit...")
p("After my colleague came in, I did not find my coffee.", "Postquam collēga intrāvit, caffeam meam nōn invēnī.")
p("When the meeting is long, I sleep.", "Cum conventus longus est, dormiō.")
p("When the teacher came in, the students went quiet.", "Ubi magister intrāvit, discipulī tacuērunt.")
t("Notice: {cum} and {ubi} can take now or then. {Postquam} usually looks back: after it happened.")

# ---------------- 2. because ----------------
t("Part two. Because.")
t("{Quod} means because. {Quia} also means because. Same job.")
p("I am tired today.", "Hodiē fessus sum.")
p("I am tired today because I work a lot.", "Hodiē fessus sum quod multum labōrō.")
p("Titus is not coming.", "Titus nōn venit.")
p("Titus is not coming because he is busy.", "Titus nōn venit quia occupātus est.")
t("The rule. The because-part gives the reason. It can come after the main sentence, or in front of it.")
t("Spot it: {quod} or {quia} starts a mini-sentence with a normal verb. Read: because.")
t("Build it.")
p("I am angry.", "Īrātus sum.")
p("I am angry because...", "Īrātus sum quod...")
p("I am angry because my colleague drinks my coffee.", "Īrātus sum quod collēga caffeam meam bibit.")
p("I am angry because my colleague drinks my coffee again.", "Īrātus sum quia collēga caffeam meam iterum bibit.")
t("Now the reason goes to the front.")
p("Because my colleague drinks my coffee, I am angry.", "Quod collēga caffeam meam bibit, īrātus sum.")
p("And my colleague?", "Et collēga?")
p("My colleague is happy because he drinks my coffee.", "Collēga laetus est quod caffeam meam bibit.")
p("Of course.", "Certē.")
t("A small warning. {Quod} has a second job. Sometimes it means which. That is next episode. For today: {quod} plus a reason equals because.")

# ---------------- 3. if / unless ----------------
t("Part three. If, and unless.")
t("{Sī} means if. {Nisi} means unless: if not.")
p("I am tired today.", "Hodiē fessus sum.")
p("If I am tired, I stay at home.", "Sī fessus sum, domī maneō.")
p("I have time.", "Tempus habeō.")
p("If I have time, I drink coffee.", "Sī tempus habeō, caffeam bibō.")
p("Unless I hurry, I miss the train.", "Nisi festīnō, trāmen āmittō.")
t("The rule. The if-part is the condition. The other part tells you what happens then.")
t("Spot it: {sī} or {nisi} starts a mini-sentence. The comma comes at the end of it.")
t("Build it.")
p("If my colleague drinks my coffee...", "Sī collēga caffeam meam bibit...")
p("If my colleague drinks my coffee, I am angry.", "Sī collēga caffeam meam bibit, īrātus sum.")
p("If my colleague drinks my coffee, I give him nothing.", "Sī collēga caffeam meam bibit, eī nihil dō.")
p("Unless I hurry...", "Nisi festīnō...")
p("Unless I hurry, my colleague drinks my coffee.", "Nisi festīnō, collēga caffeam meam bibit.")
p("Unless I hurry in the morning, my colleague drinks my coffee.", "Nisi māne festīnō, collēga caffeam meam bibit.")
p("So I hurry every day.", "Itaque cotīdiē festīnō.")
t("Careful with {nisi}. It is {sī} plus {nōn}: if not.")

# ---------------- 4. although ----------------
t("Part four. Although.")
t("{Quamquam} means although. Very often the other half has {tamen}: still, all the same.")
p("I am tired.", "Fessus sum.")
p("Although I am tired, I work.", "Quamquam fessus sum, labōrō.")
p("The coffee is expensive.", "Caffea cāra est.")
p("Although the coffee is expensive, I still buy it.", "Quamquam caffea cāra est, tamen eam emō.")
t("The rule. {Quamquam} gives a fact. The main sentence says: it happens anyway.")
t("Spot it: {quamquam} at the start. Often {tamen} in the second half.")
t("Build it.")
p("Although the coffee is mine...", "Quamquam caffea mea est...")
p("Although the coffee is mine, my colleague drinks it.", "Quamquam caffea mea est, collēga eam bibit.")
p("Although the coffee is mine, my colleague still drinks it.", "Quamquam caffea mea est, collēga tamen eam bibit.")
p("Although my colleague does not like coffee...", "Quamquam collēga caffeam nōn amat...")
p("Although my colleague does not like coffee, he still drinks it.", "Quamquam collēga caffeam nōn amat, tamen eam bibit.")
p("Although the meeting is long, I do not sleep.", "Quamquam conventus longus est, nōn dormiō.")
p("But my colleague sleeps.", "Sed collēga dormit.")
t("When you hear {quamquam}, expect a {tamen}. But {tamen} can also stand alone. Then it means: however.")

# ---------------- 5. swap the link ----------------
t("Part five. Swap the link. This is the heart of today.")
t("One plain sentence. Then the same sentence with each link. The front word changes, and the second half changes to fit.")
p("I am tired.", "Fessus sum.")
p("When I am tired, I drink coffee.", "Cum fessus sum, caffeam bibō.")
p("Because I am tired, I stay at home.", "Quod fessus sum, domī maneō.")
p("If I am tired, I stay at home.", "Sī fessus sum, domī maneō.")
p("Unless I am tired, I go to the gym.", "Nisi fessus sum, ad gymnasium eō.")
p("Although I am tired, I still work.", "Quamquam fessus sum, tamen labōrō.")
t("Again, with the weather.")
p("The weather is bad.", "Tempestās mala est.")
p("When the weather is bad, I stay at home.", "Cum tempestās mala est, domī maneō.")
p("Because the weather is bad, we stay at home.", "Quod tempestās mala est, domī manēmus.")
p("If the weather is bad, I read at home.", "Sī tempestās mala est, domī legō.")
p("Although the weather is bad, we walk outside.", "Quamquam tempestās mala est, forīs ambulāmus.")
t("And one more, with the dog.")
p("The dog is ill.", "Canis aeger est.")
p("Because the dog is ill, I call the doctor.", "Quod canis aeger est, medicum vocō.")
p("Although the dog is ill, he eats his food.", "Quamquam canis aeger est, cibum edit.")
p("When the dog is hungry, he looks for food.", "Cum canis ēsurit, cibum quaerit.")
p("After the dog had a run, he slept under the table.", "Postquam canis cucurrit, sub mēnsā dormīvit.")

# ---------------- 6. ear quiz ----------------
t("Ear quiz. You hear the Latin, then a short pause. Say the English in your head. Then I give you the answer.")
q("Cum caput dolet, medicīnam capiō.", "When my head hurts, I take medicine.")
q("Quia ientāculum nōn ēdī, ēsuriō.", "Because I did not eat breakfast, I am hungry.")
q("Sī iānuam aperis, canis exit.", "If you open the door, the dog goes out.")
q("Quamquam pluvia cadit, birotā vehor.", "Although it is raining, I ride my bike.")
q("Postquam vesperī cēnāvimus, pelliculam spectāvimus.", "After we had dinner in the evening, we watched a film.")
q("Nisi lentē loquitur, nēmō intellegit.", "Unless he speaks slowly, nobody understands.")
q("Laetus sum quod venīs.", "I am happy because you are coming.")
q("Quamquam Titus iuvenis est, sapiēns est.", "Although Titus is young, he is wise.")
q("Ubi pluvia dēsiit, forīs ambulāvimus.", "When the rain stopped, we walked outside.")
q("Sī Mārcus venit, cēnam parō.", "If Marcus comes, I make dinner.")
q("Quamquam multās epistulās accēpī, nūllī tamen respondī.", "Although I received many emails, I answered none.")
q("Cum laophorium nōn venit, īrātus sum.", "When the bus does not come, I am angry.")

# ---------------- recap + teaser ----------------
t("Recap. Four kinds of link, one key line each.")
p("When I am tired, I drink coffee.", "Cum fessus sum, caffeam bibō.")
p("I am angry because my colleague drinks my coffee.", "Īrātus sum quod collēga caffeam meam bibit.")
p("Unless I hurry, my colleague drinks my coffee.", "Nisi festīnō, collēga caffeam meam bibit.")
p("Although the coffee is mine, my colleague still drinks it.", "Quamquam caffea mea est, collēga tamen eam bibit.")
t("Next time: sentences inside sentences. The colleague who drinks my coffee.")
p("The colleague who drinks my coffee...", "Collēga quī caffeam meam bibit...")
t("Who is he? And what does he say? Next episode. {Valē!} Now the Latin alone, twice.")

